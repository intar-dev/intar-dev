#!/usr/bin/env bun

// Emits a TypeScript type and a standalone ajv validator for each contract
// schema the Worker parses, from the schemas `intar-contracts-typegen` wrote.
// The validators are plain modules with no runtime compile, so they run in a
// Worker, and one module per schema keeps them tree-shakeable.

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020";
import standaloneCode from "ajv/dist/standalone";
import { compile } from "json-schema-to-typescript";

const generated = fileURLToPath(new URL("../src/generated", import.meta.url));
const outDir = resolve(generated, "contracts");
const schemas = [
  "bridge-message-v9",
  "source-bundle-v2",
  "source-bundle-meta-v2",
  "oci-manifest-v1",
  "oci-machine-config-v1",
  "oci-kino-config-v1",
  "scenario-revision-v1",
  "machine-spec-v1",
];
const banner =
  "// Generated by apps/web/scripts/generate-contract-validators.ts from\n" +
  "// schemas/<name>.schema.json. Do not edit.\n";

// schemars marks Rust integer widths with `format`; ajv knows none of them.
// The fixed-width ones become bounds; 64-bit ones lose precision in a JS
// number anyway and keep only their `minimum`.
const integerBounds: Record<string, [number, number] | null> = {
  uint8: [0, 0xff],
  uint16: [0, 0xffff],
  uint32: [0, 0xffff_ffff],
  int32: [-0x8000_0000, 0x7fff_ffff],
  uint64: null,
  int64: null,
  uint: null,
  int: null,
  double: null,
};

function withoutFormats(node: unknown): unknown {
  if (Array.isArray(node)) return node.map(withoutFormats);
  if (node === null || typeof node !== "object") return node;
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(node)) {
    out[key] = withoutFormats(value);
  }
  const format = out.format;
  if (typeof format === "string") {
    if (!(format in integerBounds)) {
      throw new Error(`unknown schema format ${format}`);
    }
    delete out.format;
    const bounds = integerBounds[format];
    if (bounds) {
      out.minimum = Math.max(bounds[0], Number(out.minimum ?? bounds[0]));
      out.maximum = Math.min(bounds[1], Number(out.maximum ?? bounds[1]));
    }
  }
  return out;
}

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

for (const name of schemas) {
  const schema = withoutFormats(
    JSON.parse(readFileSync(resolve(generated, `schemas/${name}.schema.json`), "utf8")),
  ) as { title: string };
  const type = schema.title;

  const types = await compile(structuredClone(schema), type, {
    bannerComment: banner,
    additionalProperties: false,
    strictIndexSignatures: true,
  });
  writeFileSync(resolve(outDir, `${name}.ts`), types);

  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: true },
    strictTypes: false,
  });
  const code = standaloneCode(ajv, ajv.compile(schema));
  if (/\brequire\(|new Function|\beval\(/.test(code)) {
    throw new Error(`${name}: the validator needs a runtime compile or require`);
  }
  writeFileSync(resolve(outDir, `${name}.validate.js`), `${banner}${code}`);
  writeFileSync(
    resolve(outDir, `${name}.validate.d.ts`),
    `${banner}import type { ErrorObject } from "ajv";\n` +
      `import type { ${type} } from "./${name}";\n\n` +
      `declare const validate: ((data: unknown) => data is ${type}) & {\n` +
      `  errors?: ErrorObject[] | null;\n};\n` +
      "export default validate;\n",
  );
}
